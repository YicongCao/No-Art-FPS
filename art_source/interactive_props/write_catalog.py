"""Compile authored placements into a Godot resource catalog included by exports."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[2]
entries=json.loads((ROOT/'art_source/interactive_props/placements.json').read_text())
kinds=list(dict.fromkeys(e['kind'] for group in entries.values() for e in group))
s='extends RefCounted\n\n# Generated by art_source/interactive_props/write_catalog.py.\nconst MODELS = {\n'+''.join('\t"%s":preload("res://assets/models/interactive_props/%s.glb"),\n'%(k,k) for k in kinds)+'}\nconst PLACEMENTS = '+json.dumps(entries,ensure_ascii=False)+'\n'
(ROOT/'scripts/maps/interactive_prop_catalog.gd').write_text(s)
